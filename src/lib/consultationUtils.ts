import { ConsultationNote, PrescriptionItem } from "@/types";

interface ConsultationData {
  callId: string;
  consultantName: string;
  patientName: string;
  consultationDate: string;
  consultationTime: string;
  duration: number;
  chiefComplaint: string;
  notes: ConsultationNote[];
  prescriptions: PrescriptionItem[];
}

/**
 * Generate a text-based consultation report
 */
export const generateTextReport = (data: ConsultationData): string => {
  const formatTime = (seconds: number): string => {
    const hours = Math.floor(seconds / 3600);
    const minutes = Math.floor((seconds % 3600) / 60);
    const secs = seconds % 60;

    if (hours > 0) {
      return `${hours}h ${minutes}m ${secs}s`;
    }
    return `${minutes}m ${secs}s`;
  };

  const report = `
═══════════════════════════════════════════════════════════════
                    CONSULTATION REPORT
═══════════════════════════════════════════════════════════════

CONSULTATION DETAILS
────────────────────────────────────────────────────────────────
Consultation ID:     ${data.callId}
Consultant:          ${data.consultantName}
Patient Name:        ${data.patientName}
Date:                ${data.consultationDate}
Time:                ${data.consultationTime}
Duration:            ${formatTime(data.duration)}
Chief Complaint:     ${data.chiefComplaint}

CLINICAL NOTES
────────────────────────────────────────────────────────────────
${
  data.notes.length > 0
    ? data.notes
        .map((note) => {
          const categoryLabel =
            note.category.charAt(0).toUpperCase() + note.category.slice(1);
          return `[${note.timestamp}] (${categoryLabel}):
${note.content}`;
        })
        .join("\n\n")
    : "No notes recorded."
}

PRESCRIPTIONS
────────────────────────────────────────────────────────────────
${
  data.prescriptions.length > 0
    ? data.prescriptions
        .map((p) => {
          return `Medicine:    ${p.medicineName}
Dosage:       ${p.dosage}
Frequency:    ${p.frequency}
Duration:     ${p.duration}
${p.notes ? `Notes:        ${p.notes}` : ""}`;
        })
        .join("\n\n")
    : "No prescriptions issued."
}

SUMMARY
────────────────────────────────────────────────────────────────
Total Notes:         ${data.notes.length}
Total Prescriptions: ${data.prescriptions.length}
Generated:           ${new Date().toLocaleString()}

═══════════════════════════════════════════════════════════════
              Generated by Recommendic Medical Platform
═══════════════════════════════════════════════════════════════
  `;

  return report;
};

