/**
 * Download report as a file
 */
export const downloadReport = (
  content: string,
  filename: string,
  mimeType: string = "text/plain",
) => {
  const element = document.createElement("a");
  element.setAttribute(
    "href",
    `data:${mimeType};charset=utf-8,${encodeURIComponent(content)}`,
  );
  element.setAttribute("download", filename);
  element.style.display = "none";

  document.body.appendChild(element);
  element.click();
  document.body.removeChild(element);
};

/**
 * Export report as PDF
 */
export const downloadPDFReport = async (
  data: ConsultationData,
  filename: string,
) => {
  const htmlContent = generateHtmlReport(data);

  // If html2pdf library is available
  try {
    // You'll need to install html2pdf: npm install html2pdf.js
    const element = document.createElement("div");
    element.innerHTML = htmlContent;

    const opt = {
      margin: 10,
      filename: filename,
      image: { type: "jpeg", quality: 0.98 },
      html2canvas: { scale: 2 },
      jsPDF: { orientation: "portrait", unit: "mm", format: "a4" },
    };

    // @ts-ignore - html2pdf is global
    if (typeof html2pdf !== "undefined") {
      // @ts-ignore
      html2pdf().set(opt).from(element).save();
    } else {
      console.warn(
        "html2pdf library not available. Downloading as HTML instead.",
      );
      downloadReport(
        htmlContent,
        filename.replace(".pdf", ".html"),
        "text/html",
      );
    }
  } catch (error) {
    console.error("Error generating PDF:", error);
  }
};

/**
 * Send report to server
 */
export const sendReportToServer = async (
  data: ConsultationData,
  endpoint: string,
): Promise<boolean> => {
  try {
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        ...data,
        generatedAt: new Date().toISOString(),
      }),
    });

    if (!response.ok) {
      throw new Error(`Server error: ${response.statusText}`);
    }

    return true;
  } catch (error) {
    console.error("Error sending report to server:", error);
    return false;
  }
};
